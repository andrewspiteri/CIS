  let svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">`;
  svg += rect(0, 0, width, height, tokens.soft, tokens.soft, 0);
  if (minimalShell) {
    svg += `<rect x="0" y="0" width="${width}" height="88" fill="${tokens.dark}"/>`;
    svg += text("CIS application", canvasX, 54, 20, tokens.bg, 650);
    svg += text(screen.route || "/", width - canvasX, 54, 13, "#CBD5E1", 600, 'text-anchor="end"');
  } else {
    svg += `<rect x="0" y="0" width="270" height="${height}" fill="${tokens.dark}"/>`;
    svg += text("CIS application", 32, 54, 20, tokens.bg, 650);
    ["Overview", "Work", "Customers", "Operations", "Settings"].forEach((item, index) => {
      const y = 118 + index * 54;
      if (index === 1) svg += rect(20, y - 28, 230, 42, "#172554", "#172554", tokens.radiusSm);
      svg += text(item, 42, y, 14, index === 1 ? tokens.bg : "#CBD5E1", index === 1 ? 650 : 500);
    });
