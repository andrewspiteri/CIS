  return svg;
}
function renderScreen(screen) {
  const useTable = provenance.componentTemplates.includes("component.table");
  const useFilters = provenance.componentTemplates.includes("component.filter-bar");
  const useForm = provenance.componentTemplates.includes("component.form");
  let content = useFilters ? filterBar() : "";
  content += useTable ? standardTable(canvasX, useFilters ? 342 : 250, canvasWidth)
    : useForm ? standardForm(canvasX, useFilters ? 342 : 250, 760)
    : card("Feature content", "Compose feature content from the reusable component catalog without changing the shared shell.", canvasX, 250, canvasWidth, 280);
  content += card("Design provenance", `${provenance.shellTemplate} · ${provenance.guidelineSha256.slice(0, 22)}…`, canvasX, 770, canvasWidth, 94);
  return applicationShell(screen, content);
}

