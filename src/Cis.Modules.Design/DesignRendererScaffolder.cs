  const stats = await sharp(output).stats();
  if (metadata.width !== width || metadata.height !== height || stats.channels.every(channel => channel.stdev === 0)) {
    throw new Error(`Invalid or blank render: ${screen.file}`);
  }
  console.log(`Rendered ${screen.file} (${metadata.width}x${metadata.height})`);
}
