  return svg + text(label, x + 30, y + 16, 13, state === "disabled" ? "#94A3B8" : tokens.slate, 500);
}
function radioGroup(label, options, x, y, selected = 0) {
  let svg = text(label, x, y, 13, tokens.slate, 650);
  options.forEach((option, index) => {
    const oy = y + 28 + index * 32;
    svg += `<circle cx="${x + 10}" cy="${oy}" r="9" fill="${tokens.bg}" stroke="${index === selected ? tokens.blue : tokens.border}"/>`;
    if (index === selected) svg += `<circle cx="${x + 10}" cy="${oy}" r="5" fill="${tokens.blue}"/>`;
    svg += text(option, x + 30, oy + 5, 13, tokens.slate, 500);
  });
  return svg;
}
