function checkboxControl(label, x, y, state = "unchecked") {
  const checked = state === "checked" || state === "indeterminate";
  let svg = rect(x, y, 20, 20, checked ? tokens.blue : tokens.bg, checked ? tokens.blue : tokens.border, 4);
  if (state === "checked") svg += `<path d="M ${x + 4} ${y + 10} L ${x + 8} ${y + 15} L ${x + 16} ${y + 5}" fill="none" stroke="${tokens.bg}" stroke-width="2"/>`;
