using System.Text.Json;

namespace Cis.Modules.Design;

internal sealed record WireframeScreen(string Id, string FrontendType, string Name, string Route, string Platform, string Purpose);

internal static class DesignRendererScaffolder
{
    // Definition previews and governed delivery designs share the same control primitives.
    internal static string ControlPrimitives => Template[Template.IndexOf("function esc(", StringComparison.Ordinal)..Template.IndexOf("function pageHeader(", StringComparison.Ordinal)];

    public static string Render(
        string feature,
        IReadOnlyList<WireframeScreen> screens,
        string shell,
        IReadOnlyList<string> components,
        string guidelinePath,
        string guidelineSha256,
        string uiDirectionPath,
        string uiDirectionSha256,
        string wireframeSha256)
    {
        var options = new JsonSerializerOptions { WriteIndented = true };
        var screenJson = JsonSerializer.Serialize(screens.Select(screen => new
        {
            id = Slug(screen.Id),
            frontendType = screen.FrontendType,
            name = screen.Name,
            route = screen.Route,
            platform = screen.Platform,
            purpose = screen.Purpose,
            state = "primary",
            viewport = "desktop",
            file = $"{Slug(screen.Id)}--primary--desktop.png",
        }), options);
        var componentJson = JsonSerializer.Serialize(components.Distinct(StringComparer.OrdinalIgnoreCase), options);
        return Template
            .Replace("__FEATURE__", EscapeJs(feature), StringComparison.Ordinal)
            .Replace("__SHELL__", EscapeJs(shell), StringComparison.Ordinal)
            .Replace("__COMPONENTS__", componentJson, StringComparison.Ordinal)
            .Replace("__SCREENS__", screenJson, StringComparison.Ordinal)
            .Replace("__GUIDELINE_PATH__", EscapeJs(guidelinePath), StringComparison.Ordinal)
            .Replace("__GUIDELINE_SHA__", EscapeJs(guidelineSha256), StringComparison.Ordinal)
            .Replace("__UI_DIRECTION_PATH__", EscapeJs(uiDirectionPath), StringComparison.Ordinal)
            .Replace("__UI_DIRECTION_SHA__", EscapeJs(uiDirectionSha256), StringComparison.Ordinal)
            .Replace("__WIREFRAME_SHA__", EscapeJs(wireframeSha256), StringComparison.Ordinal);
    }

    private static string Slug(string value)
    {
        var chars = value.Trim().ToLowerInvariant().Select(character =>
            char.IsLetterOrDigit(character) ? character : '-').ToArray();
        return string.Join('-', new string(chars).Split('-', StringSplitOptions.RemoveEmptyEntries));
    }

    private static string EscapeJs(string value)
        => value.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal);

