function standardButton(label, x, y, w = 154, variant = "secondary", state = "default") {
  const palette = { primary: [tokens.blue, tokens.bg, tokens.blue], secondary: [tokens.bg, tokens.dark, tokens.border],
    destructive: [tokens.critical, tokens.bg, tokens.critical], ghost: ["transparent", tokens.slate, "transparent"] };
  let [fill, ink, stroke] = palette[variant] ?? palette.secondary;
  if (state === "disabled") [fill, ink, stroke] = ["#E2E8F0", "#94A3B8", "#CBD5E1"];
  const prefix = state === "loading" ? "... " : "";
  const focus = state === "focused" ? `<rect x="${x - 3}" y="${y - 3}" width="${w + 6}" height="48" rx="11" fill="none" stroke="${tokens.blue}" stroke-width="2"/>` : "";
  return focus + rect(x, y, w, 42, fill, stroke, tokens.radiusSm)
    + text(prefix + label, x + 16, y + 27, 14, ink, 650);
}
function textInput(label, value, x, y, w = 320, state = "default", helper = "") {
  const stroke = state === "error" ? tokens.critical : state === "focused" ? tokens.blue : tokens.border;
